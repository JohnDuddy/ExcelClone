@pytest.mark.parametrize(("formula", "expected"), EDGE_CASES)
def test_function_edge_cases(formula: str, expected: object) -> None:
    result = FormulaEvaluator(Workbook()).evaluate(formula)

    if isinstance(expected, float) and math.isfinite(expected):
        assert result == pytest.approx(expected)
    else:
        assert result == expected
